"""User data in Postgres: accounts, learning progress, enrolled tools,
reviews, reactions, saved lessons, comments, reports and tool requests.

These tables live in the "public" schema next to the catalog ("graph").
They are created on first use, and new tables or indexes are added to an
existing database automatically (CREATE ... IF NOT EXISTS). Tools and lessons
are stored by their public ids (e.g. "python", "python.decorators"), not as
foreign keys, so reloading the catalog never touches user data.
"""
